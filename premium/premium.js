(()=>{
 'use strict';
 const $=selector=>document.querySelector(selector);
 const status=$('#status'),gate=$('#gate'),members=$('#members'),msg=$('#message');
 const DAYS_KEY='clube_premium_planner_v1',NOTES_KEY='clube_premium_notes_v1';
 const api='/api/premium';
 async function call(method='GET',data){
   const opts={method,credentials:'include',cache:'no-store',headers:{Accept:'application/json'}};
   if(data){opts.headers['Content-Type']='application/json';opts.body=JSON.stringify(data)}
   const r=await fetch(api,opts);
   return {ok:r.ok,status:r.status,data:await r.json().catch(()=>({}))};
 }
 function showGate(message=''){
   gate.hidden=false;members.hidden=true;members.replaceChildren();status.hidden=true;msg.textContent=message;
 }
 function readDays(){
   try{const list=JSON.parse(localStorage.getItem(DAYS_KEY)||'[]');
     return Array.isArray(list)?list.filter(n=>Number.isInteger(n)&&n>=1&&n<=21):[];
   }catch{return []}
 }
 function updatePlanner(){
   const dayGrid=$('#days');if(!dayGrid)return;
   dayGrid.replaceChildren();const selected=readDays();
   for(let day=1;day<=21;day++){
     const b=document.createElement('button');b.type='button';
     b.className='day'+(selected.includes(day)?' selected':'');
     b.setAttribute('aria-label',`Dia ${day}`);
     b.setAttribute('aria-pressed',selected.includes(day)?'true':'false');
     b.textContent=String(day).padStart(2,'0');
     b.addEventListener('click',()=>{
       let days=readDays();days=days.includes(day)?days.filter(x=>x!==day):[...days,day].sort((a,b)=>a-b);
       try{localStorage.setItem(DAYS_KEY,JSON.stringify(days))}catch{}
       updatePlanner();
     });
     dayGrid.appendChild(b);
   }
   $('#count').textContent=selected.length;
   $('#percentage').textContent=Math.round(selected.length/21*100)+'%';
 }
 async function check(){
   try{
     const r=await call();
     if(r.ok&&r.data.authorized&&typeof r.data.html==='string'){showMembers(r.data.html)}
     else if(r.status===503)showGate('A área Premium ainda precisa ser configurada pelo administrador na Vercel.');
     else showGate();
   }catch{showGate('Não foi possível verificar o acesso. Confira a conexão e a configuração da Vercel.')}
 }
 function showMembers(trustedServerHtml){
   // The HTML is generated by our own Vercel function only after validating the signed cookie.
   members.innerHTML=trustedServerHtml;
   gate.hidden=true;members.hidden=false;status.hidden=true;
   const notes=$('#notes');
   try{notes.value=localStorage.getItem(NOTES_KEY)||''}catch{}
   let noteTimer;
   notes.addEventListener('input',()=>{
     clearTimeout(noteTimer);$('#saved').textContent='Salvando…';
     noteTimer=setTimeout(()=>{
       try{localStorage.setItem(NOTES_KEY,notes.value);$('#saved').textContent='Salvo neste aparelho'}
       catch{$('#saved').textContent='Não foi possível salvar'}
     },300);
   });
   $('#exit').addEventListener('click',async()=>{
     try{await call('POST',{action:'logout'})}catch{}
     showGate();window.scrollTo({top:0,behavior:'smooth'});
   });
   updatePlanner();
 }
 $('#unlock-form').addEventListener('submit',async e=>{
   e.preventDefault();msg.textContent='';
   const code=$('#accessCode').value.trim();if(!code)return;
   const button=$('#unlock');button.disabled=true;button.textContent='Verificando código…';
   try{
     const r=await call('POST',{action:'unlock',code});
     if(r.ok){$('#accessCode').value='';await check()}
     else msg.textContent=r.data.error||'Não foi possível validar o código.';
   }catch{msg.textContent='Falha de conexão. Tente novamente.'}
   finally{button.disabled=false;button.innerHTML='Liberar minha área Premium <span>→</span>'}
 });
 check();
})();
